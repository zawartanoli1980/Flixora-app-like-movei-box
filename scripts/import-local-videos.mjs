import {readdir, mkdir, writeFile} from 'node:fs/promises';
import {extname, basename, resolve} from 'node:path';

const root = resolve(import.meta.dirname, '..');
const videosDirectory = resolve(root, 'public/videos');
const postersDirectory = resolve(root, 'public/posters');
const outputFile = resolve(root, 'src/generatedLocalMedia.js');
const videoExtensions = new Set(['.mp4', '.webm', '.m4v']);
const posterExtensions = ['.jpg', '.jpeg', '.png', '.webp'];

await Promise.all([
  mkdir(videosDirectory, {recursive: true}),
  mkdir(postersDirectory, {recursive: true}),
]);

const [videoFiles, posterFiles] = await Promise.all([
  readdir(videosDirectory),
  readdir(postersDirectory),
]);
const videos = videoFiles.filter(file => videoExtensions.has(extname(file).toLowerCase())).sort();
const posters = new Set(posterFiles);

const slugify = value => value.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '') || 'video';
const titleize = value => value.replace(/[-_.]+/g, ' ').replace(/\b\w/g, letter => letter.toUpperCase()).trim();
const media = videos.map((file, index) => {
  const stem = basename(file, extname(file));
  const poster = posterExtensions.map(extension => `${stem}${extension}`).find(candidate => posters.has(candidate));
  const encodedVideo = encodeURIComponent(file);
  const encodedPoster = poster ? encodeURIComponent(poster) : 'default-video.svg';
  const type = extname(file).toLowerCase() === '.webm' ? 'video/webm' : 'video/mp4';
  return {
    id: `local:${slugify(stem)}-${index + 1}`,
    title: titleize(stem),
    description: 'A locally imported video from your authorized Flixora library.',
    category: 'My Library',
    type: 'Movie',
    genres: ['My Library'],
    year: new Date().getFullYear(),
    rating: 8,
    duration: 'Local video',
    image: `./posters/${encodedPoster}`,
    backdrop: `./posters/${encodedPoster}`,
    audioTracks: ['Original'],
    subtitleTracks: [],
    qualities: ['Original'],
    sources: [{
      id: `local-source-${index + 1}`,
      label: 'Local Library',
      quality: 'Original',
      type,
      url: `./videos/${encodedVideo}`,
      audioLanguages: ['Original'],
      subtitles: [],
    }],
  };
});

const source = `// This file is generated by \`npm run import:videos\`.\n// Do not add secrets or unlicensed media.\nconst assetRoot = globalThis.location?.protocol === 'file:' ? './public' : '.';\nconst records = ${JSON.stringify(media, null, 2)};\nexport const localMedia = records.map(item => ({\n  ...item,\n  image: item.image.replace(/^\\./, assetRoot),\n  backdrop: item.backdrop.replace(/^\\./, assetRoot),\n  sources: item.sources.map(source => ({...source, url: source.url.replace(/^\\./, assetRoot)})),\n}));\n`;
await writeFile(outputFile, source);
console.log(`Imported ${media.length} local video${media.length === 1 ? '' : 's'} into src/generatedLocalMedia.js`);
